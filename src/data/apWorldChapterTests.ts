interface ChapterQuestion {
  id: number;
  sec: string;
  type: "mc";
  prompt: string;
  ch: string[];
  cor: string;
  exp: string;
}

const letters = ["A", "B", "C", "D"] as const;

const readingQuestion = (
  id: number,
  prompt: string,
  choices: [string, string, string, string],
  correct: (typeof letters)[number],
  explanation: string,
): ChapterQuestion => ({
  id,
  sec: "Chapters 1–2 · Mixed Reading",
  type: "mc",
  prompt,
  ch: choices.map((choice, index) => `${letters[index]}) ${choice}`),
  cor: correct,
  exp: explanation,
});

const reviewQuestion = (
  id: number,
  section: string,
  prompt: string,
  choices: [string, string, string, string],
  correct: (typeof letters)[number],
  explanation: string,
): ChapterQuestion => ({
  id,
  sec: section,
  type: "mc",
  prompt,
  ch: choices.map((choice, index) => `${letters[index]}) ${choice}`),
  cor: correct,
  exp: explanation,
});

const inMixedOrder = (questions: ChapterQuestion[], order: number[]): ChapterQuestion[] =>
  order.map((questionNumber, index) => ({
    ...questions[questionNumber - 1],
    id: index + 1,
  }));

